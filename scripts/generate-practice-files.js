async function workbook(sheetName, columns, rows, file) {
    const wb = new ExcelJS.Workbook()
    wb.creator = 'PromptMaster — ملف تدريب (بيانات وهمية)'
    const ws = wb.addWorksheet(sheetName, { views: [{ rightToLeft: true, state: 'frozen', ySplit: 1 }] })
    ws.columns = columns
    ws.getRow(1).font = { bold: true }
    rows.forEach(row => ws.addRow(row))
    ws.addRow([])
    ws.addRow(['ملف تدريب من PromptMaster — كل الأسامي والأرقام وهمية.'])
    await wb.xlsx.writeFile(path.join(outDir, file))
}

